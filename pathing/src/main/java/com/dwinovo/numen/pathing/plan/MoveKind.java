package com.dwinovo.numen.pathing.plan;

/** 走法。每种走法在 {@link Moves} 里有且只有一个实现:前提与代价两个纯函数。 */
public enum MoveKind {
    /** 平走:进相邻一列、同一个节点高度;可以挖开挡路的格、在脚下搭桥。 */
    WALK,
    /** 斜走:进斜对角一列,可以斜着上一级或下一级;不改地形。 */
    DIAGONAL,
    /** 上一级:进相邻一列、高一个节点;楼梯正面走上去,整块跳上去;可以挖开、可以垫一块台阶。 */
    ASCEND,
    /** 下一级:走出边沿,落到相邻一列低一个节点处。 */
    DESCEND,
    /** 下落:走出边沿,落到相邻一列低两个节点以上处(水里、梯子上接住,或摔在地上)。 */
    FALL,
    /** 跑酷:跳过一到三格的空隙,落在同一高度或高一级。 */
    PARKOUR,
    /** 垫柱:原地起跳,在脚下放一块。 */
    PILLAR,
    /** 向下挖:挖掉脚下那一格,落下一级。 */
    DOWNWARD,
    /** 攀爬:顺着梯子、藤蔓这类可攀爬的格上下一格。 */
    CLIMB,
    /** 游:在水里上下或平着挪一格。 */
    SWIM
}
